/**
 * The lint rule catalogue: one entry per stable code, with the teaching text that does not depend on the
 * spec (title, default severity, why, fix, docs). `lint.ts` fills in the spec-specific `message`.
 *
 * Severity contract: `error` means the network would reject the spec at registration or update (checked
 * against FluxOS 8.20.0 `appValidator.js`, `appUtilities.js` and `portManager.js`). `warning` means it will
 * be accepted but something is probably wrong, costs money you did not plan for, or fails at install or run
 * time. `info` is context that helps you decide. Anything unverified is a warning at most and the entry says
 * UNVERIFIED in its `source`.
 *
 * Plain language everywhere: concrete, no hype, no em dashes, no emoji.
 *
 * Pure and framework-free. No Node built-ins, no DOM.
 */

import type { LintSeverity } from './types.ts';

export type LintCategory =
  | 'identity'
  | 'shape'
  | 'instances'
  | 'resources'
  | 'image'
  | 'network'
  | 'config'
  | 'storage'
  | 'placement'
  | 'subscription'
  | 'enterprise'
  | 'practice';

export interface LintCodeMeta {
  code: string;
  title: string;
  severity: LintSeverity;
  category: LintCategory;
  /** The network or operational reason, one or two sentences. */
  why: string;
  /** What to do about it. */
  fix: string;
  docs?: string;
  /** Where the rule comes from (FluxOS file or FACTS section). `UNVERIFIED` marks a judgement call. */
  source: string;
  /**
   * How well the rule is known. Optional so older consumers keep working; when absent it is derived by
   * `lintBasis`: `unverified` if `source` says UNVERIFIED, otherwise `source`.
   *
   * - `source`     the rule (or the number in it) was read in the FluxOS source or a FluxOS component
   * - `inference`  standard Docker, DNS or Linux behaviour, an image's own docs, or a judgement call:
   *                reasonable, but not something Flux's code enforces
   * - `unverified` FACTS.md itself marks it UNVERIFIED or says the behaviour was not tested
   */
  basis?: LintBasis;
}

export type LintBasis = 'source' | 'inference' | 'unverified';

/** The provenance of a catalogue entry: its explicit `basis`, else derived from `source`. */
export function lintBasis(meta: Pick<LintCodeMeta, 'source' | 'basis'>): LintBasis {
  if (meta.basis) return meta.basis;
  return /UNVERIFIED/.test(meta.source) ? 'unverified' : 'source';
}

