// Adapted from fluxcommunity/server/scripts/bake-fallback.ts
// Regenerates src/data/baked.ts from the live upstreams. Run from the repo root:
//   npm --prefix server run bake
// Review the diff before committing: it is only a last-resort floor for a cold start with no upstream.
import { writeFileSync } from 'node:fs';
import { loadConfig, upstreamOrigins } from '../src/config.ts';
import { UpstreamClient } from '../src/core/upstream.ts';
import type { Baked } from '../src/data/fallback.ts';
import { AppsApi } from '../src/flux/apps.ts';
import { DaemonApi } from '../src/flux/daemon.ts';
import { StatsApi } from '../src/flux/stats.ts';
import { summariseCapacity, summariseGeo } from '../src/services/fleet.ts';

const BLOCKS = 120;

const cfg = loadConfig({});
const client = new UpstreamClient({
  hosts: upstreamOrigins(cfg),
  userAgent: cfg.upstream.userAgent,
  timeoutMs: 30_000,
});
const daemon = new DaemonApi(client, cfg.upstream.fluxApi);
const stats = new StatsApi(client, cfg.upstream.stats);
const apps = new AppsApi(client, cfg.upstream.fluxApi[0] as string);

const height = await daemon.blockCount();
const tip = await daemon.block(height);
if (!tip) throw new Error('tip block missing');
const counts = await daemon.nodeCount();
const rows = await stats.fleet();
const cap = summariseCapacity(rows);
const geo = summariseGeo(rows);
const [registered, running] = [await apps.registered(), await apps.running()];
if (!cap.capacity || !cap.versions.fluxos || !cap.versions.daemon) throw new Error('fleet data incomplete');

// getblock is cached upstream for an hour per height, so walking back 120 heights is cheap and polite.
const blocks: Baked['blocks'] = [];
for (let h = tip.height - BLOCKS + 1; h <= tip.height; h++) {
  const b = h === tip.height ? tip : await daemon.block(h);
  if (!b) throw new Error(`block ${h} missing`);
  blocks.push([b.height, b.time, b.txCount]);
}

const baked: Baked = {
  bakedAt: new Date().toISOString(),
  height: tip.height,
  tipTimeSec: tip.time,
  nodes: counts,
  capacity: { ...cap.capacity, reporting: cap.capacity.reporting ?? 0 },
  apps: { registered: registered.size, running: [...running].filter((n) => registered.has(n)).length },
  versions: { fluxos: cap.versions.fluxos, daemon: cap.versions.daemon },
  blocks,
  geo: {
    located: geo.located,
    total: geo.total,
    countries: geo.countries.map((c) => [c.code, c.name, c.tiers.cumulus, c.tiers.nimbus, c.tiers.stratus]),
    points: geo.points.map((p) => [p.lat, p.lon, p.t[0], p.t[1], p.t[2], p.cc ?? '']),
  },
};

const out = `// Generated by server/scripts/bake-fallback.ts on ${baked.bakedAt}. Do not edit by hand.
import type { Baked } from './fallback.ts';

// biome-ignore format: generated data
export const BAKED: Baked = ${JSON.stringify(baked)};
`;
writeFileSync(new URL('../src/data/baked.ts', import.meta.url), out);
console.log(
  `baked height ${baked.height}, ${baked.nodes.total} nodes, ${baked.geo.points.length} geo points, ${baked.blocks.length} blocks`,
);
