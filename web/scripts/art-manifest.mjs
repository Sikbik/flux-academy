export function writeArtManifest() {
  const art = readArt();
  const ids = art.map((a) => a.id);

  const lines = [];
  lines.push(
    '/**',
    " * Art manifest: the Academy's generated artwork.",
    ' *',
    ' * GENERATED by web/scripts/optimize-art.mjs. Do not edit by hand. Prompts and originals live in',
    ' * assets-src/ (PROMPTS.md records every prompt). Provenance and usage notes: web/public/art/README.md.',
    ' *',
    ' * Using the art: emblems, medals and the bench plate are emissive light on pure black, so',
    ' * `mix-blend-mode: screen` (or additive blending in WebGL) removes the box: those carry',
    " * `blend: 'screen'`. The certificate backdrop is an opaque plate (`blend: 'normal'`). The sprites",
    " * (`sprite`) say how to composite them: 'alpha' means real transparency (bokeh, streak), 'additive' means",
    ' * light on pure black for screen or additive blending only (dirt). Prefer `<picture>` with the `avif`',
    ' * source first and `src` (WebP) as the fallback. `width` and `height` are the file size in pixels; draw',
    ' * at half that or less for a crisp result on a 2x display.',
    ' */',
    '',
    "export type ArtGroup = 'tracks' | 'modules' | 'labs' | 'atmosphere' | 'medals' | 'social';",
    "export type ArtAccent = 'flux' | 'cumulus' | 'nimbus' | 'stratus';",
    "export type ArtBlend = 'screen' | 'normal';",
    '',
    'export interface ArtAsset {',
    '  /** Public URL of the WebP. Always present. */',
    '  src: string;',
    '  /** Public URL of the AVIF, present only where it is meaningfully smaller than the WebP. */',
    '  avif?: string;',
    '  width: number;',
    '  height: number;',
    '  /** Average colour as #rrggbb, for placeholders and the blur-up background. */',
    '  avg: string;',
    '  /** A description for screen readers. Empty exactly when `decorative` is true. */',
    '  alt: string;',
    '  /** True for atmosphere and backdrops: render with `alt=""` and `aria-hidden`. */',
    '  decorative?: boolean;',
    "  /** 'screen' for emissive art on pure black, 'normal' for opaque plates. */",
    '  blend: ArtBlend;',
    '  /** The one accent colour of the piece (tier colours only appear on tiers, tracks and ranks). */',
    '  accent: ArtAccent;',
    '  group: ArtGroup;',
    '  /**',
    '   * Where the lit content sits, as [left, top, right, bottom] fractions of the frame (everything above',
    '   * 12 percent luminance). Anything outside is black margin: safe to crop, safe to align by.',
    '   */',
    '  box: readonly [number, number, number, number];',
    '  /** True when the file carries a real alpha channel (the bokeh and streak sprites). */',
    '  alpha?: boolean;',
    '  /**',
    "   * Set on the scene sprites, and says how to composite them: 'alpha' = real transparency in the file",
    "   * (draw normally, or additively), 'additive' = light on pure black with no alpha channel (screen or",
    '   * additive blending only).',
    '   */',
    "  sprite?: 'alpha' | 'additive';",
    '}',
    '',
    'export type ArtId =',
  );
  for (const id of ids) lines.push(`  | ${q(id)}`);
  lines[lines.length - 1] += ';';
  lines.push('', 'export const ART: Record<ArtId, ArtAsset> = {');
  for (const a of art) {
    lines.push(`  ${q(a.id)}: {`);
    lines.push(`    src: ${q(a.src)},`);
    if (a.avif) lines.push(`    avif: ${q(a.avif)},`);
    lines.push(`    width: ${a.width},`);
    lines.push(`    height: ${a.height},`);
    lines.push(`    avg: ${q(a.avg)},`);
    lines.push(`    alt: ${q(a.alt)},`);
    if (a.decorative) lines.push('    decorative: true,');
    lines.push(`    blend: ${q(a.blend)},`);
    lines.push(`    accent: ${q(a.accent)},`);
    lines.push(`    group: ${q(a.group)},`);
    lines.push(`    box: [${(a.box ?? [0, 0, 1, 1]).join(', ')}],`);
    if (a.alpha) lines.push('    alpha: true,');
    if (a.sprite) lines.push(`    sprite: ${q(a.sprite)},`);
    lines.push('  },');
  }
  lines.push('};', '');

  lines.push(
    '/** Every art id, in manifest order. */',
    'export const ART_IDS = Object.keys(ART) as ArtId[];',
    '',
    'export function isArtId(id: string): id is ArtId {',
    '  return Object.hasOwn(ART, id);',
    '}',
    '',
    '/** The manifest entry for an id. Ids are a closed union, so a typo is a type error. */',
    'export function art(id: ArtId): ArtAsset {',
    '  return ART[id];',
    '}',
    '',
    '/** Track (tier) id to its emblem. */',
    'export const TRACK_ART = {',
  );
  for (const t of ['cumulus', 'nimbus', 'stratus']) {
    if (ids.includes(`track-${t}`)) lines.push(`  ${t}: ${q(`track-${t}`)},`);
  }
  lines.push('} as const satisfies Record<string, ArtId>;', '', LOOKUPS);

  writeFileSync(artTs, lines.join('\n'));
  writeArtReadme(art);
  return { art: art.length };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const r = writeArtManifest();
  console.log(`wrote ${artTs} (${r.art} art entries)`);
}
